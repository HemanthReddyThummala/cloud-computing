"""PUBLISHING stage (ADR-07, ADR-17): one Notion page per job, never two.

Plan: from the SUMMARIZING and EXTRACTING_FRAMES checkpoints a deterministic list of top-level blocks
is built (same job -> same list):
  0. marker paragraph "Notes generated by Video Notes Agent · job <job_id> · source: <youtube url>"
  1. Summary, Key points, Sections (each with a link to its time in the video)
  2. Key frames (only if frames were selected): a note that captions come from the transcript, then one
     image block per extracted frame with its LLM caption (timestamp link + caption + why it was chosen),
     and a note if some selected frames could not be captured.
A job with no frames gets a text-only page.

Idempotency (spec §6 "no job duplicated on Notion"): before writing, the stage RECONCILES — it lists the
parent's child pages, and a page with the same title whose FIRST block contains this job's marker is
this job's page. Its existing top-level blocks are counted and only the rest of the plan is written
(appends are in plan order, so what exists is always a prefix). This covers redelivery after a crash, a
retry after a 429, and writes whose outcome was unknown (5xx / connection lost): the next attempt reads
what was committed instead of writing blindly. Frames are uploaded (File Upload API) only for image
blocks that are still missing, right before they are attached (uploads expire after 1 h unattached).

A frame whose upload Notion rejects permanently is replaced by a short note and reported as warning
``FRAME_UPLOAD_FAILED``; ``frames_published`` is counted from the image blocks actually on the page, so
the job ends COMPLETED_WITH_WARNINGS (runner rule). Every request takes a ``Provider.NOTION`` permit.
"""
from __future__ import annotations

import base64
from typing import Any

from notesagent.common.config import Settings
from notesagent.common.errors import FatalStageError, PipelineError
from notesagent.worker.notion import NotionClient
from notesagent.worker.stages import StageContext, StageOutput

TEXT_LIMIT = 2000
FRAME_KEY = "__frame__"
FRAMES_NOTE = ("Frames are captured from the video at the times shown. Each caption was written by the AI from "
               "what is said at that moment (the transcript); it was not generated from the image.")


# ---------------------------------------------------------------- block helpers (pure)
def rich(text: str, *, link: str | None = None, italic: bool = False, color: str | None = None) -> list[dict]:
    """Rich text items, each at most 2000 characters (Notion limit)."""
    text = str(text or "")
    items = []
    for start in range(0, max(len(text), 1), TEXT_LIMIT):
        part = text[start:start + TEXT_LIMIT]
        if not part:
            continue
        item: dict[str, Any] = {"type": "text", "text": {"content": part}}
        if link:
            item["text"]["link"] = {"url": link}
        if italic or color:
            item["annotations"] = {"italic": italic, "color": color or "default"}
        items.append(item)
    return items


def block(kind: str, rich_text: list[dict]) -> dict[str, Any]:
    return {"object": "block", "type": kind, kind: {"rich_text": rich_text}}


def mmss(seconds: float) -> str:
    total = int(seconds)
    hours, rest = divmod(total, 3600)
    return f"{hours}:{rest // 60:02d}:{rest % 60:02d}" if hours else f"{rest // 60}:{rest % 60:02d}"


def watch_url(video_id: str, seconds: float | None = None) -> str:
    base = f"https://www.youtube.com/watch?v={video_id}"
    return base if seconds is None else f"{base}&t={int(seconds)}s"


def marker_text(job_id: Any) -> str:
    return f"job {job_id}"


def page_title(job: dict[str, Any]) -> str:
    title = " ".join(str(job.get("video_title") or "").split())
    return (title or f"YouTube video {job['video_id']}")[:TEXT_LIMIT]


def frame_caption(frame: dict[str, Any], video_id: str) -> list[dict]:
    t = float(frame["timestamp_sec"])
    caption = " ".join(str(frame.get("caption") or "").split())
    reason = " ".join(str(frame.get("reason") or "").split())
    return (rich(f"{mmss(t)}", link=watch_url(video_id, t)) + rich(f" — {caption}")
            + (rich(f" Why it was chosen: {reason}", italic=True) if reason else []))


def build_plan(job_id: Any, job: dict[str, Any], summary: dict[str, Any], frames: dict[str, Any]) -> list[dict]:
    video_id = job["video_id"]
    source = job.get("youtube_url") or watch_url(video_id)
    plan = [block("paragraph", rich(f"Notes generated by Video Notes Agent · {marker_text(job_id)} · source: ",
                                    color="gray") + rich(source, link=source, color="gray"))]
    plan += [block("heading_2", rich("Summary")), block("paragraph", rich(summary.get("summary") or ""))]
    if summary.get("key_points"):
        plan.append(block("heading_2", rich("Key points")))
        plan += [block("bulleted_list_item", rich(p)) for p in summary["key_points"]]
    if summary.get("sections"):
        plan.append(block("heading_2", rich("Sections")))
        for section in summary["sections"]:
            start = float(section.get("start_sec") or 0)
            plan.append(block("heading_3", rich(mmss(start), link=watch_url(video_id, start))
                              + rich(f" {section.get('title') or ''}")))
            plan += [block("bulleted_list_item", rich(p)) for p in section.get("points") or []]
    requested = int(frames.get("requested") or 0)
    extracted = list(frames.get("frames") or [])
    if requested:
        plan.append(block("heading_2", rich("Key frames")))
        plan.append(block("paragraph", rich(FRAMES_NOTE, italic=True, color="gray")))
        plan += [{FRAME_KEY: i} for i in range(len(extracted))]
        missing = requested - len(extracted)
        if missing > 0:
            plan.append(block("paragraph", rich(f"{missing} of {requested} selected frames could not be captured "
                                                f"from the video, so they are not shown.", italic=True)))
    return plan


def plain_text(notion_block: dict[str, Any]) -> str:
    content = notion_block.get(notion_block.get("type") or "", {}) or {}
    return "".join(str(r.get("plain_text") or (r.get("text") or {}).get("content") or "")
                   for r in content.get("rich_text") or [])


# ---------------------------------------------------------------- reconciliation
async def find_existing_page(client: NotionClient, parent_id: str, title: str, job_id: Any) -> str | None:
    """This job's page under ``parent_id``: a child page with the same title whose first block carries
    the job marker. Other pages (other jobs, same video) are never touched."""
    cursor, marker = None, marker_text(job_id)
    while True:
        listing = await client.list_children(parent_id, cursor)
        for child in listing.get("results") or []:
            if child.get("type") != "child_page" or (child.get("child_page") or {}).get("title") != title:
                continue
            first = (await client.list_children(child["id"], page_size=1)).get("results") or []
            if first and marker in plain_text(first[0]):
                return child["id"]
        if not listing.get("has_more"):
            return None
        cursor = listing.get("next_cursor")


# ---------------------------------------------------------------- the stage
def make_publish_stage(settings: Settings, transport=None):
    async def materialize(client: NotionClient, blocks: list[dict], frames: list[dict], video_id: str,
                          warnings: list[dict]) -> list[dict]:
        """Upload frames still needed (just before attaching) and turn placeholders into image blocks."""
        out = []
        for entry in blocks:
            if FRAME_KEY not in entry:
                out.append(entry)
                continue
            index = entry[FRAME_KEY]
            frame = frames[index]
            data = base64.b64decode(frame["image"]["data_base64"])
            try:
                upload_id = await client.upload_image(f"frame-{index + 1:02d}-{int(frame['timestamp_sec'])}s.jpg", data)
            except PipelineError as error:
                if error.retryable:
                    raise
                warnings.append({"code": "FRAME_UPLOAD_FAILED", "timestamp_sec": frame["timestamp_sec"],
                                 "reason": error.code})
                out.append(block("paragraph", rich(f"The frame at {mmss(float(frame['timestamp_sec']))} could not "
                                                   f"be uploaded to Notion.", italic=True)))
                continue
            out.append({"object": "block", "type": "image",
                        "image": {"type": "file_upload", "file_upload": {"id": upload_id},
                                  "caption": frame_caption(frame, video_id)}})
        return out

    async def publish(ctx: StageContext) -> StageOutput:
        summary, frames = ctx.checkpoints.get("SUMMARIZING"), ctx.checkpoints.get("EXTRACTING_FRAMES")
        if summary is None or frames is None:
            raise FatalStageError("PUBLISH_INPUT_MISSING", "The notes or frames of this job are missing.")
        parent = ctx.job.get("notion_parent_id") or settings.notion_default_parent_id
        if not parent:
            raise FatalStageError("NOTION_PARENT_MISSING", "No Notion destination: the job has no notion_parent_id "
                                                           "and NOTION_DEFAULT_PARENT_ID is not configured.")
        parent = str(parent)
        title = page_title(ctx.job)
        plan = build_plan(ctx.job_id, ctx.job, summary, frames)
        token = await ctx.get_notion_token()                           # per-job credential mailbox (ADR-03)
        client = NotionClient(settings, token, ctx.limiter, transport=transport)
        warnings: list[dict] = []
        try:
            page_id = await find_existing_page(client, parent, title, ctx.job_id)
            resumed = page_id is not None
            existing = await client.all_children(page_id) if resumed else []
            if len(existing) > len(plan):
                raise FatalStageError("NOTION_PAGE_CONFLICT", "The job's Notion page has unexpected extra content.")
            remaining = await materialize(client, plan[len(existing):], list(frames.get("frames") or []),
                                          ctx.job["video_id"], warnings)
            size, url = settings.notion_blocks_per_request, None
            if page_id is None:
                created = await client.create_page(parent, rich(title), remaining[:size])
                page_id, url, remaining = created["id"], created.get("url"), remaining[size:]
            for start in range(0, len(remaining), size):
                await client.append_children(page_id, remaining[start:start + size])
            if url is None:
                url = (await client.retrieve_page(page_id)).get("url")
            final = await client.all_children(page_id)
        finally:
            await client.aclose()

        requested = int(frames.get("requested") or 0)
        published = min(sum(1 for b in final if b.get("type") == "image"), requested)
        result = {"notion_page_url": url, "frames_requested": requested, "frames_published": published}
        checkpoint = {"notion_page_id": page_id, **result, "blocks": len(final), "resumed": resumed}
        return StageOutput(result=result, checkpoint=checkpoint, warnings=warnings)

    return publish
